-- anim_spec.lua — contract for Weave.tween (API-v0 §2, M8/ADR-0008). Wow layer:
-- the shared driver over the fake clock (advanceTime fires OnUpdate; GetTime starts
-- at 1000). Linear easing in most cases so intermediate values are exact.

local helper = dofile("tests/wow_helper.lua")

describe("Weave.tween: reactivo que se desliza hacia el valor de una señal", function()

  describe("siembra y animación básica", function()

    it("se siembra en el valor actual del target, sin animar", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(42)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      assert_eq(a:peek(), 42, "nace en el valor del target")
      assert_false(a:animating(), "no anima al sembrarse")
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 42, "sin cambios en el target, no se mueve")
    end)

    it("al cambiar el target, desliza desde el valor actual hasta la nueva meta", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      assert_true(a:animating(), "empieza a animar al cambiar el target")
      helper.advanceTime(0.25); assert_eq(a:peek(), 25)
      helper.advanceTime(0.25); assert_eq(a:peek(), 50)
      helper.advanceTime(0.5);  assert_eq(a:peek(), 100)
      assert_false(a:animating(), "deja de animar al llegar")
    end)

    it("respeta el easing (outQuad va por delante a mitad de tiempo)", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.outQuad })
      target:set(100)
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 75, "outQuad(0.5)=0.75 → 75%")
    end)

    it("un literal como target: se siembra y nunca anima", function()
      local W = helper.loadWeaveWow()
      local a = W.tween(50, { duration = 1, easing = W.easing.linear })
      assert_eq(a:peek(), 50)
      assert_false(a:animating())
      helper.advanceTime(1)
      assert_eq(a:peek(), 50, "un literal no reactivo no dispara ninguna animación")
    end)

  end)

  describe("re-targeting", function()

    it("si el target cambia a media animación, la nueva arranca desde el valor actual", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50, "a mitad de camino")
      target:set(0) -- re-target hacia 0, desde 50 (no desde 100)
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 25, "arranca desde 50, no da un salto atrás")
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 0)
    end)

    it("re-apuntar en el instante en que termina (ping-pong) no lo congela", function()
      -- el re-arm cae DENTRO del onTick que lo da por terminado: un effect que
      -- reacciona a :animating()=false lo manda de vuelta. El driver debe volver a
      -- engancharlo, no dejarlo animando-pero-congelado.
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      W.effect(function()
        if not a:animating() and a:peek() == 100 then target:set(0) end
      end)
      target:set(100)
      helper.advanceTime(1) -- llega a 100 → el effect re-apunta a 0
      assert_eq(a:peek(), 100, "toca el techo")
      assert_true(a:animating(), "re-arranca de vuelta, no se queda parado")
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50, "baja desde 100 (si estuviera congelado seguiría en 100)")
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 0)
    end)

  end)

  describe(":animating() y coordinación de entrada/salida", function()

    it("es false al sembrarse, true mientras anima, false al llegar", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      assert_false(a:animating())
      target:set(10)
      assert_true(a:animating())
      helper.advanceTime(1)
      assert_false(a:animating())
    end)

    it("shown = abierto or animating mantiene el frame durante el fundido de salida", function()
      local W = helper.loadWeaveWow()
      local abierto = W.signal(false)
      local goal = W.computed(function() return abierto() and 1 or 0 end)
      local a = W.tween(goal, { duration = 1, easing = W.easing.linear })
      local frame = helper.newMockFrame()
      W.bind(frame, "shown", W.computed(function() return abierto() or a:animating() end))

      assert_false(frame._set.shown, "empieza oculto (cerrado y quieto)")
      abierto:set(true)
      assert_true(frame._set.shown, "visible al abrir")
      helper.advanceTime(1)
      abierto:set(false) -- cierra: anima 1→0, debe SEGUIR visible
      assert_true(frame._set.shown, "sigue visible mientras se cierra")
      helper.advanceTime(1)
      assert_false(frame._set.shown, "se oculta al terminar la salida")
    end)

  end)

  describe("arrays (color)", function()

    it("un target array anima canal a canal", function()
      local W = helper.loadWeaveWow()
      local target = W.signal({ 1, 0, 0 })
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set({ 0, 1, 0 }) -- rojo → verde
      helper.advanceTime(0.5)
      local v = a:peek()
      assert_eq(v[1], 0.5)
      assert_eq(v[2], 0.5)
      assert_eq(v[3], 0)
    end)

  end)

  describe("taint", function()

    it("target secret: degrada al fallback y reanuda al volver un valor normal", function()
      local W = helper.loadWeaveWow({ issecretvalue = helper.isFakeSecret })
      local target = W.signal(10) -- sin fallback: expone el secret tal cual
      local a = W.tween(target, { duration = 1, easing = W.easing.linear, fallback = 0 })
      assert_eq(a:peek(), 10, "sembrado con un valor normal")
      helper.silently(function() target:set(helper.newFakeSecret()) end)
      assert_eq(a:peek(), 0, "degrada al fallback con un target secret")
      assert_false(a:animating(), "no anima hacia un secret")
      target:set(80)
      helper.advanceTime(1)
      assert_eq(a:peek(), 80, "reanuda cuando vuelve un valor normal")
    end)

  end)

  describe("rendimiento y disposal", function()

    it("coste cero en reposo: al terminar, el valor no cambia y no re-anima", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      helper.advanceTime(1)
      assert_eq(a:peek(), 100)
      assert_false(a:animating())
      helper.advanceTime(5) -- en reposo
      assert_eq(a:peek(), 100, "sin animaciones activas, el driver no mueve nada")
    end)

    it("driver compartido: dos tweens avanzan con un solo frame ticker", function()
      local W = helper.loadWeaveWow()
      local before = helper.frameCount()
      local t1 = W.signal(0); local a1 = W.tween(t1, { duration = 1, easing = W.easing.linear })
      local t2 = W.signal(0); local a2 = W.tween(t2, { duration = 1, easing = W.easing.linear })
      t1:set(1); t2:set(1)
      assert_eq(helper.frameCount() - before, 1, "un único frame para todas las animaciones")
      helper.advanceTime(1)
      assert_eq(a1:peek(), 1)
      assert_eq(a2:peek(), 1)
    end)

    it("dispose() desengancha el tween del driver y del target", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50)
      a:dispose()
      assert_false(a:animating(), "dispose detiene la animación")
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50, "tras dispose ya no avanza")
      target:set(999)
      helper.advanceTime(1)
      assert_eq(a:peek(), 50, "desenganchado del target")
    end)

    it("scope:dispose() libera el tween creado dentro de su run()", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local sc = W.scope()
      local a
      sc:run(function() a = W.tween(target, { duration = 1, easing = W.easing.linear }) end)
      target:set(100)
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50)
      sc:dispose()
      assert_false(a:animating())
      helper.advanceTime(0.5)
      assert_eq(a:peek(), 50, "el tween muere con su scope")
    end)

  end)


  describe("snap: saltar a un valor sin interpolar (FR Coffer 2026-08-23)", function()

    it("salta al valor en el acto, sin interpolar", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(100)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:snap(40)
      assert_eq(a:peek(), 40, "el valor es 40 YA, no dentro de un rato")
    end)

    it("teletransporta y SIGUE: re-apunta al destino actual desde el valor saltado", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(100) -- el destino ya vale 100: nadie lo va a mover
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:snap(40)
      assert_true(a:animating(), "queda camino hasta el destino → anima")
      helper.advanceTime(0.5); assert_eq(a:peek(), 70, "sube desde 40, no desde 100")
      helper.advanceTime(0.5); assert_eq(a:peek(), 100)
      assert_false(a:animating())
    end)

    it("snap al valor del destino no enciende animating (salto seco)", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(100)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:snap(100)
      assert_eq(a:peek(), 100)
      assert_false(a:animating(), "nada que animar: no arranca el driver")
      helper.advanceTime(1)
      assert_eq(a:peek(), 100)
    end)

    it("a media animación: salta y re-apunta al mismo destino desde el nuevo origen", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      helper.advanceTime(0.5); assert_eq(a:peek(), 50)
      a:snap(0)
      assert_eq(a:peek(), 0, "vuelve al origen en el acto")
      assert_true(a:animating(), "sigue teniendo el mismo destino: 100")
      helper.advanceTime(0.5); assert_eq(a:peek(), 50, "el reloj de la animación se reinicia")
      helper.advanceTime(0.5); assert_eq(a:peek(), 100)
    end)

    it("snap al destino DURANTE una animación la corta y baja animating a false", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      target:set(100)
      helper.advanceTime(0.5)
      a:snap(100) -- "salta al final ya"
      assert_eq(a:peek(), 100)
      assert_false(a:animating(), "el tween queda desarmado, no colgado en true")
      helper.advanceTime(1)
      assert_eq(a:peek(), 100, "y el driver ya no lo toca")
    end)

    it("arrays (color): salta los N componentes y sigue hacia la meta", function()
      local W = helper.loadWeaveWow()
      local target = W.signal({ 100, 100, 100 })
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:snap({ 0, 50, 100 })
      local v = a:peek()
      assert_eq(v[1], 0); assert_eq(v[2], 50); assert_eq(v[3], 100)
      helper.advanceTime(0.5)
      v = a:peek()
      assert_eq(v[1], 50); assert_eq(v[2], 75); assert_eq(v[3], 100)
    end)

    it("el siguiente cambio del destino anima desde el valor saltado", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:snap(0) -- ya está en el destino: no anima
      assert_false(a:animating())
      target:set(100)
      helper.advanceTime(0.5); assert_eq(a:peek(), 50, "arranca desde 0, el valor saltado")
    end)

    it("destino secret: salta al valor pedido y no intenta animar", function()
      local W = helper.loadWeaveWow({ issecretvalue = helper.isFakeSecret })
      local target = W.signal(0)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear, fallback = 0 })
      helper.silently(function() target:set(helper.newFakeSecret()) end)
      a:snap(40)
      assert_eq(a:peek(), 40, "el salto sí se aplica")
      assert_false(a:animating(), "no se puede interpolar hacia un secret")
      helper.advanceTime(1)
      assert_eq(a:peek(), 40)
    end)

    it("tras dispose() es un no-op", function()
      local W = helper.loadWeaveWow()
      local target = W.signal(100)
      local a = W.tween(target, { duration = 1, easing = W.easing.linear })
      a:dispose()
      a:snap(40)
      assert_eq(a:peek(), 100, "un tween muerto no se mueve")
      assert_false(a:animating())
    end)

    it("valida el argumento", function()
      local W = helper.loadWeaveWow()
      local a = W.tween(W.signal(0), { duration = 1 })
      assert_error(function() a:snap() end, "snap")
      assert_error(function() a:snap("x") end, "snap")
    end)

  end)

end)
